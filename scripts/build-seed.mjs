// Generates migrations/0002_seed.sql: the 12 sample items + demo accounts.
// Usage:  node scripts/build-seed.mjs "<demo password>"
// Passwords are hashed with the same PBKDF2 format the Worker uses.
import { writeFileSync } from 'node:fs';
import { webcrypto as crypto } from 'node:crypto';
import { seedItems } from '../public/data.js';

const password = process.argv[2];
if (!password || password.length < 10) {
  console.error('Usage: node scripts/build-seed.mjs "<demo password, 10+ chars>"');
  process.exit(1);
}

const enc = new TextEncoder();
const b64 = buf => Buffer.from(buf).toString('base64');
async function hashPassword(pw, iterations = 100000) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const key = await crypto.subtle.importKey('raw', enc.encode(pw), 'PBKDF2', false, ['deriveBits']);
  const bits = await crypto.subtle.deriveBits({ name: 'PBKDF2', hash: 'SHA-256', salt, iterations }, key, 256);
  return `pbkdf2_sha256$${iterations}$${b64(salt)}$${b64(bits)}`;
}
const q = v => v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;

const users = [
  ['U-DEMO-RES', 'resident@findback.demo', 'Aina Resident', 'resident', null],
  ['U-DEMO-SEC', 'security@findback.demo', 'Ravi Security', 'security', 'Central Park security desk'],
  ['U-DEMO-STP', 'staff.centralpark@findback.demo', 'Mei Ling (Central Park)', 'staff', 'Central Park security desk'],
  ['U-DEMO-STC', 'staff.clubhouse@findback.demo', 'Hafiz (Clubhouse)', 'staff', 'Clubhouse reception'],
  ['U-DEMO-ADM', 'admin@findback.demo', 'Township Admin', 'admin', null],
];

let sql = '-- Generated by scripts/build-seed.mjs. Sample data only.\n\n';
for (const [id, email, name, role, point] of users)
  sql += `INSERT INTO users (id, email, name, password_hash, role, collection_point) VALUES (${q(id)}, ${q(email)}, ${q(name)}, ${q(await hashPassword(password))}, ${q(role)}, ${q(point)});\n`;
sql += '\n';
for (const i of seedItems)
  sql += `INSERT INTO items (id, name, category, color, location, date, description, private_note, collection, illus_type, paint, accent, sample) VALUES (${[i.id, i.name, i.category, i.color, i.location, i.date, i.description, i.privateNote, i.collection, i.type, i.paint, i.accent].map(q).join(', ')}, 1);\n`;

writeFileSync(new URL('../migrations/0002_seed.sql', import.meta.url), sql);
console.log(`Wrote migrations/0002_seed.sql with ${users.length} demo accounts and ${seedItems.length} items.`);
